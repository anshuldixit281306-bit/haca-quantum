"""
Quantum result analyzer.

Converts Quantum Engine simulation results into
human-readable observations for the AI Tutor.
"""

from typing import Any


def analyze_counts(
    counts: dict[str, int],
    shots: int,
) -> dict[str, Any]:
    """
    Analyze measurement counts.
    """

    if shots <= 0:
        raise ValueError("shots must be greater than zero.")

    safe_counts = {
        str(state): int(count)
        for state, count in counts.items()
    }

    probabilities = {
        state: round(count / shots, 6)
        for state, count in safe_counts.items()
    }

    if not safe_counts:
        return {
            "shots": shots,
            "counts": {},
            "probabilities": {},
            "most_frequent_state": None,
            "observation": "No measurement results were returned.",
        }

    most_frequent_state = max(
        safe_counts,
        key=safe_counts.get,
    )

    highest_probability = probabilities[
        most_frequent_state
    ]

    return {
        "shots": shots,
        "counts": safe_counts,
        "probabilities": probabilities,
        "most_frequent_state": most_frequent_state,
        "highest_probability": highest_probability,
        "observation": (
            f"The state |{most_frequent_state}> was observed most "
            f"frequently with an estimated probability of "
            f"{highest_probability:.2%}."
        ),
    }


def analyze_quantum_result(
    result: dict[str, Any],
) -> dict[str, Any]:
    """
    Analyze a complete Quantum Engine result.
    """

    algorithm = result.get(
        "algorithm",
        "Quantum Experiment",
    )

    counts = result.get(
        "counts",
        {},
    )

    shots = int(
        result.get(
            "shots",
            0,
        )
    )

    analysis = analyze_counts(
        counts=counts,
        shots=shots,
    )

    analysis["algorithm"] = algorithm

    if algorithm == "Superposition":

        analysis["educational_note"] = (
            "An ideal single-qubit superposition created with "
            "a Hadamard gate should produce approximately equal "
            "probabilities for 0 and 1."
        )

    elif algorithm == "Bell State":

        analysis["educational_note"] = (
            "A Bell state demonstrates quantum entanglement. "
            "The ideal Phi+ state produces correlated 00 and 11 "
            "measurement outcomes."
        )

    elif algorithm == "Grover Search":

        target = result.get(
            "target",
            "unknown",
        )

        analysis["educational_note"] = (
            f"Grover's algorithm attempts to amplify the probability "
            f"of the marked target state |{target}>."
        )

    elif algorithm == "Quantum Teleportation":

        analysis["educational_note"] = (
            "Quantum teleportation uses entanglement and classical "
            "information to transfer quantum-state information."
        )

    else:

        analysis["educational_note"] = (
            "This result was generated by the QuantumLearn "
            "Quantum Engine."
        )

    return analysis


def generate_result_explanation(
    result: dict[str, Any],
) -> str:
    """
    Generate a simple natural-language explanation
    from a Quantum Engine result.
    """

    analysis = analyze_quantum_result(
        result
    )

    algorithm = analysis["algorithm"]
    state = analysis["most_frequent_state"]
    probability = analysis["highest_probability"]

    if state is None:
        return (
            f"{algorithm} completed, but no measurement "
            "results were available."
        )

    return (
        f"The {algorithm} experiment used "
        f"{analysis['shots']} shots. "
        f"The most frequently observed state was "
        f"|{state}> with an estimated probability of "
        f"{probability:.2%}. "
        f"{analysis['educational_note']}"
    )